# ✒️ РАЗМЕТКА ВЕРДИКТА
# ==========================================
# Вердикт уходит в parse_mode="HTML", а НЕ в "Markdown", и обратно возвращать
# нельзя. Gemini пишет в GFM, где жирный — это ДВЕ звёздочки, а legacy-Markdown
# Telegram знает только одну: "**Товар:**" приезжало пользователю буквально, со
# звёздочками в тексте. HTML заодно снимает остальные грабли legacy-режима —
# одиночный _ в тексте модели (или незакрытая *) роняли всё сообщение в фоллбэк
# без разметки, теперь спецсимволы просто экранируются.
#
# Telegram понимает только четыре сущности (&lt; &gt; &amp; &quot;), числовые
# вроде &#x27; показывает как есть, поэтому экранируем ровно & < > и ничего больше.

def esc(text: str) -> str:
    """Экранирование под Telegram HTML: только &, <, >."""
    return html.escape(str(text), quote=False)


# Ссылку разбираем до всего остального: внутри подписи могут быть звёздочки
_MD_LINK_RE = re.compile(r"\[([^\]\n]+)\]\((https?://[^\s)]+)\)")
_MD_CODE_RE = re.compile(r"`([^`\n]+)`")
# (?=\S) / (?<=\S) — не даём схватить "** " и пустые пары
_MD_BOLD_RE = re.compile(r"\*\*(?=\S)(.+?)(?<=\S)\*\*")
_MD_BOLD_UND_RE = re.compile(r"(?<!\w)__(?=\S)(.+?)(?<=\S)__(?!\w)")
_MD_STRIKE_RE = re.compile(r"~~(?=\S)(.+?)(?<=\S)~~")
# Курсив одной звёздочкой — только после того, как ** уже съедены.
# Пробел после открывающей звёздочки запрещён, поэтому маркер списка "* пункт"
# под это правило не подпадает.
_MD_ITALIC_RE = re.compile(r"(?<!\*)\*(?=\S)([^*\n]+?)(?<=\S)\*(?!\*)")
# Подчёркивание — только на границе слова, иначе развалятся user_id и
# @perekup_dvizheniya_bot, если модель их процитирует
_MD_ITALIC_UND_RE = re.compile(r"(?<!\w)_(?=\S)([^_\n]+?)(?<=\S)_(?!\w)")
_MD_HEADING_RE = re.compile(r"^[ \t]*#{1,6}[ \t]*(.+?)[ \t]*$", re.M)
_MD_BULLET_RE = re.compile(r"^([ \t]*)[*+][ \t]+", re.M)


def md_to_html(text: str) -> str:
    """Markdown от Gemini → HTML-подмножество Telegram.

    Экранирование идёт ПЕРВЫМ: после него в строке не остаётся сырых < и >,
    и теги, которые мы добавляем ниже, уже нельзя спутать с текстом модели
    (модель пишет и "экран < 5 дюймов", и "маржа > 10 000").
    """
    out = esc(text)

    out = _MD_LINK_RE.sub(
        # Кавычку в URL Telegram бы не простил внутри href — проценткодируем
        lambda m: f'<a href="{m.group(2).replace(chr(34), "%22")}">{m.group(1)}</a>',
        out,
    )
    out = _MD_CODE_RE.sub(r"<code>\1</code>", out)
    out = _MD_HEADING_RE.sub(r"<b>\1</b>", out)
    out = _MD_BOLD_RE.sub(r"<b>\1</b>", out)
    out = _MD_BOLD_UND_RE.sub(r"<b>\1</b>", out)
    out = _MD_STRIKE_RE.sub(r"<s>\1</s>", out)
    out = _MD_ITALIC_RE.sub(r"<i>\1</i>", out)
    out = _MD_ITALIC_UND_RE.sub(r"<i>\1</i>", out)
    out = _MD_BULLET_RE.sub(r"\1• ", out)

    # Непарные ** остаться уже не могут ничем, кроме мусора: показывать их
    # пользователю — это ровно тот баг, из-за которого всё и переделывалось
    return out.replace("**", "")


# Теги, которые мы вообще умеем ставить. По ним же чинится обрезка.
_TAG_RE = re.compile(r"<(/?)(b|i|s|u|code|pre|a)\b[^>]*>", re.I)


def truncate_html(text: str, limit: int, ellipsis: str = "…") -> str:
    """Обрезает HTML под лимит, не разрывая тег и не бросая его незакрытым.

    Наивный срез по символам ломал бы сообщение: Telegram отвергает "<b>текст"
    без закрывающего тега, и вердикт уезжал бы в фоллбэк без разметки — то есть
    ровно там, где он и так длинный и нечитаемый.
    """
    if len(text) <= limit:
        return text

    cut = limit - len(ellipsis)
    for _ in range(3):
        if cut <= 0:
            return ellipsis[:limit]

        head = text[:cut]
        # Не режем внутри тега
        lt, gt = head.rfind("<"), head.rfind(">")
        if lt > gt:
            head = head[:lt]
        # Не режем внутри сущности (&amp;)
        amp, semi = head.rfind("&"), head.rfind(";")
        if amp > semi and len(head) - amp <= 8:
            head = head[:amp]

        stack = []
        for m in _TAG_RE.finditer(head):
            name = m.group(2).lower()
            if m.group(1):
                for i in range(len(stack) - 1, -1, -1):
                    if stack[i] == name:
                        del stack[i]
                        break
            else:
                stack.append(name)

        tail = ellipsis + "".join(f"</{n}>" for n in reversed(stack))
        if len(head) + len(tail) <= limit:
            return head + tail
        cut -= len(tail)  # закрывающие теги не влезли — отступаем и пробуем снова

    return ellipsis[:limit]


def html_to_plain(text: str) -> str:
    """HTML → голый текст для фоллбэка: сырые <b> хуже, чем текст без разметки."""
    return html.unescape(re.sub(r"<[^>]+>", "", text))


def build_reply(verdict: str, sources: list, grounded: bool, limit_text: str,
                total: int = 0, show_city_hint: bool = False) -> str:
    """Собирает итоговое сообщение: вердикт + источники + остаток проверок.

    Результат — HTML (см. md_to_html): разметку модели конвертируем, свою
    дописываем тегами, всё динамическое экранируем.

    total — сколько источников реально пришло в grounding_metadata. Это число
    считает бот, а не модель, поэтому его можно показывать.
    """
    if not grounded:
        # Цена посчитана по памяти: ссылки показывать нельзя, они к ней не относятся.
        # Дисклеймер модель ставит сама, страхуемся только если она его потеряла.
        # Сверяем по "без проверки рынка" в СЫРОМ вердикте: разметку модель могла
        # намотать прямо на дисклеймер, а при МАЛО ДАННЫХ она тоже пишет
        # "вилка ориентировочная" — по одному слову проверка бы ложно срабатывала.
        sources_block = "" if "без проверки рынка" in verdict else f"\n\n{esc(NO_DATA_DISCLAIMER)}"
    elif sources:
        links = "\n".join(
            f'• <a href="{esc(uri).replace(chr(34), "%22")}">{esc(label)}</a>'
            for label, uri in sources
        )
        header = f"🔎 Источники цен ({total}"
        header += f", показаны первые {len(sources)}):" if total > len(sources) else "):"
        sources_block = f"\n\n{header}\n{links}"
    else:
        sources_block = ""

    # Подсказка про регион ставится по факту "город не задан", а не по тому, что
    # модель написала в строке Рынок: если регион был назван в объявлении, модель
    # считала по нему, и утверждать "считали по Москве" было бы неправдой.
    # Формулировка поэтому условная и верна в обоих случаях.
    city_block = f"\n\n{esc(CITY_HINT)}" if show_city_hint else ""

    # Рекламная строка — часть футера, а не вердикта: значит она входит в расчёт
    # длины и обрезка её не съедает. Режется всегда вердикт.
    footer = (f"{sources_block}{city_block}"
              f"\n\n📉 Остаток проверок: {esc(limit_text)}"
              f"\n\n{AD_LINE}")
    # Лимит сообщения в Telegram — 4096 символов. Режем вердикт, а не источники.
    verdict_html = truncate_html(md_to_html(verdict), 4096 - len(footer) - 1)

    return f"{verdict_html}{footer}"


async def send_verdict(status_msg: Message, text: str):
    """Отдаёт вердикт пользователю. Если HTML почему-то не разобрался — шлём
    голый текст: сырые теги на экране хуже, чем текст без разметки.

    Клавиатуры под вердиктом нет намеренно: ссылка «Анализ выполнен здесь» —
    часть HTML-футера сообщения (AD_LINE), а не кнопка. Кнопка пересчёта в
    другом режиме здесь была и удалена — см. комментарий у verdict_prompt().
    """
    try:
        await status_msg.edit_text(text, parse_mode="HTML")
    except TelegramBadRequest as e:
        logging.warning("HTML в вердикте не разобрался, шлём без разметки: %s", e)
        await status_msg.edit_text(html_to_plain(text))


async def download_photos(photos_list: list) -> list:
    """Фото Telegram → части запроса к Gemini.

    Telegram отдаёт готовый JPEG — шлём байты как есть. Part.from_bytes только
    заворачивает их в inline_data; PIL.Image библиотека пересохранила бы в PNG
    (pil_to_blob) прямо в event loop.
    """
    images = []
    for photo in photos_list:
        photo_io = BytesIO()
        await bot.download(photo, destination=photo_io)
        images.append(
            types.Part.from_bytes(data=photo_io.getvalue(), mime_type="image/jpeg")
        )
    return images


# Оптимизировано: убран лишний аргумент free_checks. Проверка лимитов идет напрямую из БД.
async def process_single_or_album(user_id: int, photos_list: list, caption: str,
                                  status_msg: Message, limit_token: str | None = None):
    try:
        images_for_gemini = await download_photos(photos_list)

        # Дату сообщаем явно: у модели нет представления о "сегодня", а цены нужны
        # свежие. Подпись пользователя уходит в рамке — см. build_user_prompt.
        # Регион берём из профиля; если города нет — дефолт, и тогда под вердиктом
        # покажем подсказку. Один и тот же prompt уходит в оба вызова, так что
        # персонализация стоит одну строку токенов, а не лишний запрос.
        user_city, _ = db.get_city_state(user_id)
        region, region_is_default = resolve_region(user_city)
        prompt = build_user_prompt(caption, region)

        # Режим читаем один раз, до вызова Gemini: смена режима посреди анализа
        # не должна менять вердикт на полпути.
        mode = db.get_mode(user_id)

        # Вариант B: сборщику цен хватает одного кадра, чтобы опознать модель;
        # все фото нужны только оценщику, который смотрит дефекты. Так альбом
        # из 10 фото не оплачивается дважды.
        price_contents = [prompt] + images_for_gemini[:1]
        verdict_contents = [prompt] + images_for_gemini

        response, grounded, price_block, price_response = await ask_gemini_two_step(
            price_contents, verdict_contents, caption or "", mode
        )

        # Пустой text бывает при блокировке или MALFORMED_FUNCTION_CALL. Отдавать
        # пользователю голый футер нельзя — уходим в except, там возврат лимита.
        if not response.text:
            finish = response.candidates[0].finish_reason if response.candidates else None
            raise RuntimeError(f"Gemini вернул пустой ответ, finish_reason={finish}")

        # Источники берём с первого шага: на втором поиска нет, метаданных тоже
        queries, sources, total_sources = extract_grounding(price_response)
        logging.info(
            "user=%s цены_собраны=%s запросы=%s источников=%s",
            user_id, grounded, queries, total_sources
        )

        # Лимит уже зарезервирован до вызова Gemini — здесь только читаем остаток
        limit_text = format_limit_text(user_id)

        await send_verdict(
            status_msg,
            build_reply(response.text, sources, grounded, limit_text,
                        total_sources, show_city_hint=region_is_default)
        )

    except Exception as e:
        logging.error("Анализ не удался для user=%s: %s", user_id, e, exc_info=True)

        # Анализ не дошёл до пользователя — возвращаем зарезервированную проверку
        db.refund_limit(user_id, limit_token)

        await notify_admin(
            f"⚠️ <b>Ошибка Gemini</b>\n\n"
            f"👤 Пользователь: <code>{user_id}</code>\n"
            f"Ошибка:\n<code>{html.escape(str(e))}</code>"
        )

        # Само сообщение об ошибке тоже может не уйти (сообщение удалено, бот
        # заблокирован). Без этой защиты исключение улетало бы из except: в
        # альбомной ветке — в задачу, которую никто не ждёт, то есть в пустоту.
        try:
            await status_msg.edit_text(
                "⚠️ Что-то пошло не так при анализе. Попробуй отправить картинки еще раз."
            )
        except Exception as notify_error:
            logging.error("Не удалось сообщить об ошибке пользователю %s: %s",
                          user_id, notify_error, exc_info=True)



