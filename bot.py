@dp.message(Command("give"))
async def give_subscription(message: Message):
    """Ручное начисление. Три механики сразу:

    requests — пакеты запросов; sub — безлимитная подписка (оба продаются
    сейчас); base|premium|unlimited — старый Stars-тариф, для тех легаси-
    подписчиков, у которых надо что-то поправить. Старые формы команды работают
    как раньше, чтобы не переучиваться.
    """
    if message.from_user.id != ADMIN_ID:
        return

    args = message.text.split()

    if len(args) < 3:
        await message.answer(GIVE_USAGE)
        return

    try:
        user_id = int(args[1])
    except ValueError:
        await message.answer("USER_ID должен быть числом.\n\n" + GIVE_USAGE)
        return

    kind = args[2].lower()
    db.add_user(user_id)

    if kind in ("requests", "req", "запросы"):
        try:
            qty = int(args[3])
            days = int(args[4]) if len(args) > 4 else db.REQUEST_TTL_DAYS
        except (IndexError, ValueError):
            await message.answer(GIVE_USAGE)
            return

        if qty < 1:
            await message.answer("Количество запросов должно быть больше нуля.")
            return

        expires_at = db.add_purchased_requests(user_id, qty, days=days, source='admin')
        balance = db.purchased_balance(user_id)
        expires_str = datetime.fromisoformat(expires_at).strftime('%d.%m.%Y')

        await message.answer(
            f"✅ Пользователю {user_id} начислено {qty} запросов на {days} дней "
            f"(до {expires_str}). Баланс: {balance}."
        )

        try:
            await bot.send_message(
                user_id,
                f"🎁 Тебе начислено {qty} запросов.\n"
                f"📦 На балансе: {balance}\n"
                f"⏳ Сгорают {expires_str}"
            )
        except Exception as e:
            logging.warning("Не удалось сообщить о начислении пользователю %s: %s", user_id, e)
        return

    if kind in ("sub", "безлимит", "подписка"):
        # 'sub', а не 'unlimited': последнее уже занято старым Stars-тарифом, и
        # перепутать их в поддержке — значит выдать не тот доступ.
        try:
            days = int(args[3]) if len(args) > 3 else db.UNLIMITED_DAYS
        except ValueError:
            await message.answer(GIVE_USAGE)
            return

        if days < 1:
            await message.answer("Дней должно быть больше нуля.")
            return

        until = datetime.fromisoformat(db.extend_unlimited(user_id, days))
        until_str = until.strftime('%d.%m.%Y')

        await message.answer(
            f"✅ Пользователю {user_id} включён безлимит на {days} дней (до {until_str})."
        )

        try:
            await bot.send_message(
                user_id,
                f"♾ Тебе включён безлимитный доступ на {days} дней.\n"
                f"Действует до {until_str} — анализы не списываются."
            )
        except Exception as e:
            logging.warning("Не удалось сообщить о безлимите пользователю %s: %s", user_id, e)
        return

    if kind not in ("base", "premium", "unlimited"):
        await message.answer("Неизвестный тариф.\n\n" + GIVE_USAGE)
        return

    try:
        days = int(args[3])
    except (IndexError, ValueError):
        await message.answer(GIVE_USAGE)
        return

    until = db.set_tier(user_id, kind, days)

    await message.answer(
        f"✅ Пользователю {user_id} выдан {kind.upper()} на {days} дней."
    )

    try:
        await bot.send_message(
            user_id,
            f"🎉 Вам выдан тариф {kind.upper()} на {days} дней.\n"
            f"Действует до {until.strftime('%d.%m.%Y')}."
        )
    except Exception as e:
        logging.warning("Не удалось сообщить о тарифе пользователю %s: %s", user_id, e)

