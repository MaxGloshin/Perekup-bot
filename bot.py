async def handle_qty_answer(message: Message, user_id: int) -> bool:
    """Разбор введённого количества. True — сообщение было ответом на наш вопрос.

    Не отдельный хендлер, а функция, которую зовёт catch_city_answer: aiogram
    останавливает диспетчеризацию на первом же подошедшем хендлере, даже если тот
    просто вышел по return. Два хендлера на `F.text` означали бы, что второй
    (город) не получает вообще ничего.
    """
    raw = (message.text or "").strip().replace(" ", "")
    if not raw.isdigit():
        await message.answer(
            f"Нужно число от 1 до {MAX_CUSTOM_QTY} — например, 120. Отменить — /cancel."
        )
        return True

    qty = int(raw)
    if qty < 1 or qty > MAX_CUSTOM_QTY:
        await message.answer(
            f"Можно от 1 до {MAX_CUSTOM_QTY} запросов за раз. "
            f"Нужно больше — напиши в поддержку: @realgloshin"
        )
        return True

    awaiting_qty.discard(user_id)
    await send_payment_link(message, user_id, qty)
    return True


async def send_payment_link(message: Message, user_id: int, qty: int | None = None,
                            kind: str = db.ORDER_KIND_REQUESTS):
    """Заводит заказ и отдаёт кнопку оплаты.

    Заказ пишется в БД до оплаты: подпись ссылки считается по InvId, значит
    номер нужен раньше, чем человек нажмёт кнопку.

    kind='unlimited' — покупка безлимитной подписки. Отличий у неё ровно три:
    цена берётся из константы, а не из сетки, qty в заказе означает дни, и в
    чек уходит своё наименование. Всё остальное — лимит открытых счетов,
    подпись ссылки, кнопка проверки, поллер — общее с пакетами, поэтому вторая
    копия этой функции не нужна и заводить её нельзя.
    """
    db.add_user(user_id)

    open_orders = db.count_open_orders(user_id)
    if open_orders >= MAX_OPEN_ORDERS:
        await message.answer(
            "У тебя уже несколько неоплаченных счетов. Оплати или дождись, пока "
            f"они закроются (это {ORDER_TTL_HOURS} ч), и заводи новый."
        )
        return

    if kind == db.ORDER_KIND_UNLIMITED:
        qty = UNLIMITED_DAYS
        amount = UNLIMITED_PRICE
        item_name = UNLIMITED_RECEIPT_NAME
    else:
        amount = price_for(qty)
        item_name = None

    invoice_id = db.create_order(user_id, qty, amount, kind=kind)

    try:
        # ExpirationDate не передаём: в официальном примере Robokassa его нет,
        # а неверный формат ломает счёт. Срок жизни заказа держим у себя —
        # expire_stale_orders() плюс длинное окно контрольных опросов, потому
        # что без ExpirationDate ссылка остаётся оплачиваемой и после суток.
        url = robokassa.build_payment_url(
            invoice_id=invoice_id,
            amount_rub=amount,
            qty=qty,
            item_name=item_name,
        )
    except Exception as e:
        logging.error("Не удалось сформировать ссылку Robokassa (заказ %s): %s",
                      invoice_id, e, exc_info=True)
        db.set_order_status(invoice_id, 'canceled')
        await message.answer(
            "⚠️ Не получилось сформировать счёт. Попробуй ещё раз или напиши "
            "в поддержку: @realgloshin"
        )
        await notify_admin(
            f"⚠️ <b>Ошибка формирования ссылки Robokassa</b>\n"
            f"Заказ: <code>{invoice_id}</code>, пользователь: <code>{user_id}</code>\n"
            f"<code>{html.escape(str(e))}</code>"
        )
        return

    kb = InlineKeyboardMarkup(inline_keyboard=[
        [InlineKeyboardButton(text=f"💳 Оплатить {amount} ₽", url=url)],
        [InlineKeyboardButton(text="🔄 Проверить оплату", callback_data=f"chk:{invoice_id}")],
    ])

    logging.info("Заказ %s: user=%s kind=%s qty=%s amount=%s",
                 invoice_id, user_id, kind, qty, amount)

    if kind == db.ORDER_KIND_UNLIMITED:
        active_until = db.unlimited_active_until(user_id)
        # Продлевающему сразу показываем, к чему прибавятся дни: "до 23.09" вместо
        # "30 дней от сегодня" — это разные обещания, и второе было бы неверным.
        if active_until:
            tail = (f"Сейчас подписка активна до {active_until.strftime('%d.%m.%Y')}, "
                    f"после оплаты — до "
                    f"{(active_until + timedelta(days=UNLIMITED_DAYS)).strftime('%d.%m.%Y')}.\n")
        else:
            tail = (f"После оплаты безлимит будет действовать до "
                    f"{(datetime.now() + timedelta(days=UNLIMITED_DAYS)).strftime('%d.%m.%Y')}.\n")

        await message.answer(
            f"🧾 Счёт №{invoice_id}\n\n"
            f"Товар: безлимитный доступ на {UNLIMITED_DAYS} дней\n"
            f"К оплате: {amount} ₽\n"
            f"Срок оплаты: {ORDER_TTL_HOURS} ч\n\n"
            f"{tail}"
            "Оплати по кнопке ниже — подписку включу автоматически в течение минуты "
            "после оплаты, сообщение придёт сюда же.\n"
            "Автопродления нет: следующая оплата — только твоей кнопкой.\n"
            "Чек придёт на email, который укажешь при оплате.",
            reply_markup=kb
        )
        return

    await message.answer(
        f"🧾 Счёт №{invoice_id}\n\n"
        f"Запросов: {qty}\n"
        f"К оплате: {amount} ₽ ({amount // qty} ₽ за запрос)\n"
        f"Срок оплаты: {ORDER_TTL_HOURS} ч\n\n"
        "Оплати по кнопке ниже. Запросы начислю автоматически в течение минуты "
        "после оплаты — сообщение придёт сюда же.\n"
        "Чек придёт на email, который укажешь при оплате.",
        reply_markup=kb
    )


@dp.callback_query(F.data.startswith("chk:"))
async def process_check_click(callback: CallbackQuery):
    """Внеочередная проверка одного заказа: человеку не надо ждать общий цикл."""
    user_id = callback.from_user.id

    try:
        invoice_id = int(callback.data.split(":", 1)[1])
    except ValueError:
        await callback.answer("Не понял, какой счёт проверить", show_alert=True)
        return

    order = db.get_order(invoice_id)
    if not order or order['user_id'] != user_id:
        await callback.answer("Счёт не найден", show_alert=True)
        return

    if order['status'] == 'paid':
        await callback.answer("Этот счёт уже оплачен и начислен ✅", show_alert=True)
        return

    if not robokassa.PAYMENTS_ENABLED:
        await callback.answer("Проверка оплаты сейчас недоступна", show_alert=True)
        return

    await callback.answer("Проверяю…")
    try:
        async with aiohttp.ClientSession() as session:
            state = await robokassa.get_op_state(session, invoice_id)
    except Exception as e:
        logging.warning("Ручная проверка заказа %s не удалась: %s", invoice_id, e)
        await callback.message.answer(
            "Не получилось спросить статус у Robokassa. Если деньги списаны, "
            "запросы начислятся сами — проверяю каждые полминуты."
        )
        return

    result = await apply_op_state(order, state)

    if result == 'paid':
        return  # пользователю уже ушло сообщение о зачислении
    if result == 'already':
        await callback.message.answer("✅ Этот счёт уже был зачислен.")
    elif result == 'canceled':
        await callback.message.answer(
            "❌ Оплата по этому счёту отменена или возвращена. "
            "Можно завести новый: кнопка «💰 Цены и оплата»."
        )
    elif result == 'amount_mismatch':
        await callback.message.answer(
            "⚠️ Сумма оплаты не совпала со счётом — разбираемся вручную, "
            "поддержка уже уведомлена."
        )
    else:
        await callback.message.answer(
            "Оплата пока не подтверждена. Если ты только что заплатил — подожди "
            "минуту, деньги идут не мгновенно. Начислю сам, как только увижу."
        )


async def deliver_paid_order(credited: dict):
    """Сообщает пользователю и админу о зачислении. Вызывается ровно один раз
    на заказ: credit_order() пропускает уже оплаченные."""
    user_id = credited['user_id']

    if credited.get('kind') == db.ORDER_KIND_UNLIMITED:
        await deliver_paid_unlimited(credited)
        return

    balance = db.purchased_balance(user_id)

    try:
        expires = datetime.fromisoformat(credited['expires_at']).strftime('%d.%m.%Y')
    except ValueError:
        expires = None

    text = (
        f"🎉 Оплата прошла! Начислено запросов: {credited['qty']}\n"
        f"📦 На балансе: {balance}\n"
    )
    if expires:
        text += f"⏳ Сгорают {expires}\n"
    text += (
        "\nЧек придёт на email, указанный при оплате.\n"
        "Присылай фото — можно работать 🚀"
    )

    try:
        await bot.send_message(user_id, text)
    except Exception as e:
        # Деньги уже приняты и начислены — потеря сообщения не повод терять платёж
        logging.error("Не удалось сообщить об оплате пользователю %s: %s",
                      user_id, e, exc_info=True)

    await notify_admin(
        f"💰 <b>Оплата Robokassa</b>\n"
        f"Счёт: <code>{credited['invoice_id']}</code>\n"
        f"Пользователь: <code>{user_id}</code>\n"
        f"Запросов: {credited['qty']} на {credited['amount_rub']} ₽\n"
        f"Баланс после начисления: {balance}"
    )

    # Начисление рефоводу уже в БД (одна транзакция с заказом) — здесь только
    # сообщения. Потеря сообщения бонус не отменяет.
    if credited.get('referral'):
        await deliver_referral_bonus(credited['referral'])


async def deliver_paid_unlimited(credited: dict):
    """Сообщения по оплаченной подписке. Начисление уже в БД — здесь только текст.

    Отдельной функцией, а не ветками внутри deliver_paid_order: общего в текстах
    нет ничего, кроме реферального хвоста, а начисление к этому моменту уже
    сделано одной транзакцией в credit_order.
    """
    user_id = credited['user_id']
    balance = db.purchased_balance(user_id)

    try:
        until = datetime.fromisoformat(credited['unlimited_until'])
        until_str = until.strftime('%d.%m.%Y')
    except (TypeError, ValueError):
        until_str = None

    text = f"🎉 Оплата прошла! Безлимит включён — анализы больше не списываются.\n"
    if until_str:
        text += f"♾ Действует до {until_str}\n"
    if balance:
        # Пакетные запросы никуда не делись и не тратятся, пока жива подписка —
        # человек должен это видеть, иначе решит, что за них заплатил зря.
        text += f"📦 Купленные запросы ({balance}) не тратятся, ждут своей очереди\n"
    text += (
        "\nАвтопродления нет: когда срок будет подходить к концу, напомню — "
        "продлишь кнопкой.\n"
        "Чек придёт на email, указанный при оплате.\n"
        "Присылай фото — можно работать 🚀"
    )

    try:
        await bot.send_message(user_id, text)
    except Exception as e:
        # Деньги уже приняты и подписка включена — потеря сообщения не повод
        # терять платёж
        logging.error("Не удалось сообщить о подписке пользователю %s: %s",
                      user_id, e, exc_info=True)

    await notify_admin(
        f"♾ <b>Оплата Robokassa: безлимит</b>\n"
        f"Счёт: <code>{credited['invoice_id']}</code>\n"
        f"Пользователь: <code>{user_id}</code>\n"
        f"{credited['qty']} дней за {credited['amount_rub']} ₽\n"
        f"Подписка до: {until_str or '—'}\n"
        f"Активных подписок всего: {db.active_unlimited_count()}"
    )

    if credited.get('referral'):
        await deliver_referral_bonus(credited['referral'])


async def deliver_referral_bonus(ref: dict):
    """Сообщает рефоводу и админу о реферальном начислении."""
    referrer_id = ref['referrer_id']

    if not ref['total'] and not ref['capped']:
        # Покупка меньше 5 запросов и не первая: 20% от неё — ноль целых.
        # Сообщать не о чем ни рефоводу, ни админу.
        return

    if ref['total'] > 0:
        parts = []
        if ref['bonus']:
            parts.append(f"➕ {ref['bonus']} — разово за первую покупку приглашённого")
        if ref['percent']:
            parts.append(f"➕ {ref['percent']} — {db.REF_PERCENT}% с его покупки")

        balance = db.purchased_balance(referrer_id)
        text = (
            "🎁 Реферальный бонус!\n\n"
            + "\n".join(parts)
            + f"\n\n📦 На балансе: {balance}\n"
            "♾ Реферальные запросы не сгорают.\n\n"
            "Твоя ссылка и статистика — /ref"
        )
        try:
            await bot.send_message(referrer_id, text)
        except Exception as e:
            logging.warning("Не удалось сообщить о реферальном бонусе пользователю %s: %s",
                            referrer_id, e)

    # Админа зовём и когда начислять было нечего из-за потолка: молча упереться
    # в лимит — это ровно тот случай, который надо увидеть глазами.
    cap_note = "\n⚠️ Упёрлись в потолок программы" if ref['capped'] else ""
    await notify_admin(
        f"🎁 <b>Реферальное начисление</b>\n"
        f"Рефовод: <code>{referrer_id}</code>\n"
        f"Приглашённый: <code>{ref['buyer_id']}</code>\n"
        f"Разовый бонус: {ref['bonus']}, процент: {ref['percent']}"
        f"{cap_note}"
    )


