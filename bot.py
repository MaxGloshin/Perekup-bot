@dp.callback_query(F.data.startswith("mode:"))
async def process_mode_choice(callback: CallbackQuery):
    """Сохранение режима. Один обработчик и на онбординг, и на /mode: разница
    только в том, что при знакомстве следом идёт вопрос про город."""
    user_id = callback.from_user.id
    parts = callback.data.split(":")
    mode = parts[1] if len(parts) > 1 else ""
    onboarding = len(parts) > 2 and parts[2] == MODE_ONBOARDING_SUFFIX

    db.add_user(user_id)
    if not db.set_mode(user_id, mode):
        # Кнопка из будущей/прошлой версии — молча ничего не меняем
        await callback.answer("Такого режима нет, попробуй /mode", show_alert=True)
        return

    # edit_text заодно убирает кнопки: вопрос закрыт, повторно жать нечего
    with contextlib.suppress(TelegramBadRequest):
        await callback.message.edit_text(MODE_CONFIRM[mode], parse_mode="Markdown")
    await callback.answer()

    # Знакомство продолжается вопросом о городе — и только знакомство: кнопки
    # из /mode этой ветки не касаются, иначе человек, однажды проигнорировавший
    # вопрос, получал бы его при каждой смене режима.
    if onboarding:
        _, city_asked = db.get_city_state(user_id)
        if not city_asked:
            await ask_city(callback.message, user_id)


