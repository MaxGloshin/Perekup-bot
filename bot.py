    # упрётся в тот же None и покажет экран покупки. Гейт здесь только добавил бы
    # лишний шаг «сначала подпишись, а теперь плати» — человека, которому нечем
    # платить за анализ, ведём сразу к покупке.
    #
    # 'sub' — действующая безлимитная подписка. Человек уже заплатил за то,
    # чтобы бот работал без условий; ставить ему перед каждым анализом ещё и
    # требование подписаться на канал — это продать доступ и тут же его
    # ограничить.
    #
    # Всё остальное ('daily', 'purchased', 'unlimited') гейтится как раньше.
    source, _ = next_check_source(user_id)
    if source in ('free', 'sub') or source is None:
        return True

    if await is_subscribed(user_id):
        return True

    # Запоминаем запрос даже если само сообщение сейчас задавит антиспам:
