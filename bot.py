async def gemini_generate_content(**kwargs):
    """Вызов Gemini с повтором на обрыв соединения с прокси.

    Единая точка вызова для обоих шагов анализа: сборщик цен и вердикт ходят
    через неё, чтобы повтор не пришлось дублировать (и разъезжаться) в двух
    местах — по той же причине, по которой резервирование лимита живёт в одном
    run_analysis().

    Повторяется ТОЛЬКО транспорт (PROXY_CONNECT_ERRORS): прокси не поднял
    соединение, и запрос до Gemini не дошёл вовсе. Любой ответ самого Gemini —
    503, 429, 400, пустой text — пролетает наружу нетронутым и обрабатывается
    там же, где и раньше: сборщик цен глушит его в NO_PRICE_DATA, вердикт
    доводит до общего except в process_single_or_album (возврат лимита +
    "⚠️ Ошибка Gemini" админу). Два вида ошибок не должны делить один счётчик
    попыток: у сетевого флапа пауза секундная, у перегруженного API — своя.

    Учти: у SDK внутри уже есть ОДИН собственный повтор на aiohttp-ошибку
    (_async_request_once, сон 1-10 с), поэтому до нас исключение доезжает
    после его попытки. Наши попытки идут поверх — на нестабильном прокси это
    и нужно, но в логах пауза между нашими строками будет больше расчётной.
    """
    last_error = None
    for attempt in range(1, GEMINI_PROXY_RETRY_ATTEMPTS + 1):
        try:
            return await gemini_client.aio.models.generate_content(**kwargs)
        except PROXY_CONNECT_ERRORS as e:
            last_error = e
            if attempt >= GEMINI_PROXY_RETRY_ATTEMPTS:
                break
            delay = GEMINI_PROXY_RETRY_BASE_DELAY_MS * 2 ** (attempt - 1) / 1000
            logging.warning(
                "Прокси: попытка %s из %s не удалась (%s: %s), retry через %s сек",
                attempt, GEMINI_PROXY_RETRY_ATTEMPTS, type(e).__name__, e, delay
            )
            await asyncio.sleep(delay)

    logging.error(
        "Прокси: соединение не поднялось за %s попыток, сдаёмся (%s: %s)",
        GEMINI_PROXY_RETRY_ATTEMPTS, type(last_error).__name__, last_error
    )
    raise last_error


