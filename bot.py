def fmt_thousands(value: int) -> str:
    """12345 → '12 345'. Обычный пробел, а не узкий: узкий Telegram рисует не везде."""
    return f"{value:,}".replace(",", " ")


def acquisition_report_lines() -> list[str]:
    """Строки отчёта /stats. Без разметки: теги источников — [A-Za-z0-9_-],
    экранировать в них нечего, а обычный текст Telegram не может отклонить."""
    rows = db.acquisition_stats()
    if not rows:
        return ["Пользователей пока нет."]

    total_users = sum(row[1] for row in rows)
    total_buyers = sum(row[2] for row in rows)
    total_revenue = sum(row[3] for row in rows)

    # Платежи пользователей, чьи строки удалила самоочистка /broadcast: источника
    # у них больше нет, в разрез они не попадают. Строку печатаем всегда, в том
    # числе с нулём — иначе непонятно, расхождения нет или отчёт сломался.
    orphan_revenue, orphan_payments = db.orphan_paid_revenue()

    def conversion(buyers: int, users: int) -> str:
        # Один знак после запятой: на сотнях пользователей целые проценты
        # склеивают заметно разные каналы, двух знаков рынок не заслуживает.
        return f"{buyers * 100 / users:.1f}%" if users else "—"

    lines = [
        "📊 Источники трафика (за всё время)",
        "",
        f"👥 Всего пользователей: {fmt_thousands(total_users)}",
        f"💳 Покупали хотя бы раз: {fmt_thousands(total_buyers)} "
        f"({conversion(total_buyers, total_users)})",
        f"💰 Выручка: {fmt_thousands(total_revenue)} руб.",
        f"↳ вне разреза: {fmt_thousands(orphan_revenue)} руб. "
        f"(платежей: {orphan_payments}) — от пользователей, удалённых самоочисткой "
        f"/broadcast, источник у них не сохранился",
        "",
        "По источникам (пользователи / купили / конверсия / выручка):",
        "",
    ]

    for source, users, buyers, revenue in rows:
        lines.append(
            f"🏷 {source} — {fmt_thousands(users)} / {fmt_thousands(buyers)} / "
            f"{conversion(buyers, users)} / {fmt_thousands(revenue)} руб."
        )

    lines += [
        "",
        f"Ссылка под новый источник: {source_link('<тег>')}",
        f"Тег: латиница, цифры, _ и -, до {MAX_SRC_TAG_LEN} символов.",
    ]
    return lines


@dp.message(Command("stats"))
async def acquisition_stats_cmd(message: Message):
    """Маркетинговая аналитика по источникам трафика.

    Источники без покупок показываем наравне с остальными: неэффективный канал
    видно только в сравнении, а отсортированный по выручке список кладёт такие
    строки в хвост сам.
    """
    if message.from_user.id != ADMIN_ID:
        return

    lines = acquisition_report_lines()

    # Каналов со временем может стать много, а лимит сообщения — 4096 символов.
    # Режем по строкам, а не по символам: разорванная строка отчёта бесполезна.
    chunk: list[str] = []
    size = 0
    for line in lines:
        if size + len(line) + 1 > 3800 and chunk:
            await message.answer("\n".join(chunk))
            chunk, size = [], 0
        chunk.append(line)
        size += len(line) + 1
    if chunk:
        await message.answer("\n".join(chunk))


