@dp.message(F.successful_payment)
async def on_successful_payment(message: Message):
    """Страховка, а не рабочий путь: новых счетов бот больше не выставляет.

    Оставлен намеренно после отключения продажи за звёзды. Сюда можно попасть
    только в гонке — пользователь подтвердил оплату по старому счёту ровно в
    момент деплоя, до того как pre_checkout начал отклонять. Звёзды в этот
    момент уже списаны, и удалённый хендлер означал бы списание без выдачи и
    без следа. Логика начисления не тронута: тариф выдаётся, платёж пишется в
    processed_payments, админ получает уведомление.
    """
    payment = message.successful_payment
    user_id = message.from_user.id
    charge_id = payment.telegram_payment_charge_id
    payload = payment.invoice_payload

    # Бот выставляет счета только в звёздах. Чужая валюта означает, что что-то
    # пошло не по нашему сценарию — молча проглатывать оплату нельзя.
    if payment.currency != "XTR":
        logging.error(
            "Платёж в неожиданной валюте: user=%s currency=%s amount=%s payload=%s charge_id=%s",
            user_id, payment.currency, payment.total_amount, payload, charge_id
        )
        await notify_admin(
            f"🚨 <b>Платёж в неожиданной валюте</b>\n\n"
            f"🆔 <code>{user_id}</code>\n"
            f"💱 Валюта: <code>{html.escape(str(payment.currency))}</code>\n"
            f"💰 Сумма: {payment.total_amount}\n"
            f"📦 payload: <code>{html.escape(str(payload))}</code>\n"
            f"🧾 charge_id: <code>{html.escape(str(charge_id))}</code>\n\n"
            f"Тариф НЕ выдан — разобраться вручную."
        )
        await message.answer(
            "Оплата получена, но автоматически обработать её не удалось. "
            "Мы уже разбираемся — напиши в поддержку: @realgloshin"
        )
        return

    new_tier = "base"
    if "premium" in payload:
        new_tier = "premium"
    elif "unlimited" in payload:
        new_tier = "unlimited"

    if not charge_id:
        # Без charge_id дедуплицировать нечем — обрабатываем, но помечаем в логе
        logging.warning("Платёж без telegram_payment_charge_id: user=%s payload=%s",
                        user_id, payload)

    # Telegram переотправляет апдейт, если бот не подтвердил offset. Повторная
    # выдача накинула бы ещё 30 дней бесплатно, поэтому сверяемся с журналом.
    if db.payment_already_processed(charge_id):
        logging.info("Повторная доставка платежа charge_id=%s (user=%s) — тариф не продлеваем",
                     charge_id, user_id)
        await confirm_payment(message, user_id, new_tier, repeated=True)
        return

    try:
        until_date = db.set_tier(user_id, new_tier, days=30)
    except Exception as e:
        # Звёзды уже списаны Telegram'ом. Тариф не выдан — без явного сигнала
        # админу деньги просто пропадут, поэтому шлём всё для ручной выдачи.
        logging.error(
            "НЕ УДАЛОСЬ выдать тариф после оплаты: user=%s tier=%s charge_id=%s",
            user_id, new_tier, charge_id, exc_info=True
        )
        await notify_admin(
            f"🚨 <b>ПЛАТЁЖ НЕ ЗАЧИСЛЕН — нужна ручная выдача</b>\n\n"
            f"🆔 <code>{user_id}</code>\n"
            f"⭐️ Тариф: <b>{new_tier.upper()}</b>\n"
            f"💰 Сумма: {payment.total_amount} ⭐️\n"
            f"📦 payload: <code>{html.escape(str(payload))}</code>\n"
            f"🧾 charge_id: <code>{html.escape(str(charge_id))}</code>\n\n"
            f"Ошибка:\n<code>{html.escape(str(e))}</code>\n\n"
            f"Выдать вручную:\n<code>/give {user_id} {new_tier} 30</code>"
        )
        await message.answer(
            "Оплата прошла, но активировать тариф автоматически не получилось. "
            "Мы уже знаем о проблеме и выдадим доступ вручную в ближайшее время. "
            "Если что — пиши: @realgloshin"
        )
        return

    # Записываем ПОСЛЕ выдачи: если запись упадёт, худший случай — повторная
    # выдача при редоставке. Обратный порядок в худшем случае лишил бы человека
    # оплаченного тарифа, а это хуже.
    if not db.record_payment(charge_id, user_id, new_tier, payment.total_amount, payload):
        logging.warning("charge_id=%s уже был в журнале на момент записи (user=%s)",
                        charge_id, user_id)

    username = message.from_user.username or "Скрыт"
    await notify_admin(
        f"💳 <b>Новая покупка!</b>\n\n"
        f"👤 {html.escape(message.from_user.full_name or '')}\n"
        f"🆔 <code>{user_id}</code>\n"
        f"📎 @{html.escape(username)}\n\n"
        f"⭐️ Тариф: <b>{new_tier.upper()}</b>\n"
        f"💰 Сумма: {payment.total_amount} ⭐️\n"
        f"📅 До: {until_date.strftime('%d.%m.%Y')}"
    )

    await confirm_payment(message, user_id, new_tier, repeated=False)



