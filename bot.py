# Взводится, если Robokassa отвечает "неверная подпись" или "нет такого магазина":
# это сломанные реквизиты, и долбить сервис битым запросом каждые 30 секунд
# бессмысленно. Снимается только перезапуском бота — то есть починкой .env.
poller_paused = False


async def apply_op_state(order: dict, state) -> str:
    """Реакция на ответ OpStateExt по одному заказу. Возвращает короткий код
    результата: paid | already | canceled | pending | amount_mismatch | error."""
    global poller_paused

    invoice_id = order['invoice_id']

    if state.is_config_error:
        poller_paused = True
        logging.error("Robokassa отвергла запрос (Result.Code=%s: %s) — опрос остановлен",
                      state.result_code, state.result_description)
        await notify_admin(
            f"🛑 <b>Robokassa: опрос остановлен</b>\n"
            f"Result.Code=<code>{state.result_code}</code> "
            f"({html.escape(state.result_description)})\n"
            f"Проверь ROBOKASSA_LOGIN и ROBOKASSA_PASS2 в .env и перезапусти бота."
        )
        return 'error'

    if state.result_code == robokassa.OpState.DUPLICATE_INVOICE:
        db.mark_order_checked(invoice_id)
        await notify_admin(
            f"⚠️ <b>Robokassa: две операции с одним InvId</b>\n"
            f"Счёт: <code>{invoice_id}</code> — статус не определить, разбирать в ЛК."
        )
        return 'error'

    if state.not_started:
        # Штатный ответ для неоплаченного счёта: Robokassa узнаёт об InvId только
        # в момент обращения к платёжной форме, а строку в orders мы завели раньше.
        db.mark_order_checked(invoice_id)
        return 'pending'

    if state.result_code != robokassa.OpState.OK:
        logging.warning("OpStateExt заказ %s: Result.Code=%s (%s)",
                        invoice_id, state.result_code, state.result_description)
        db.mark_order_checked(invoice_id)
        return 'error'

    if state.is_paid:
        # Подпись ссылки покрывает OutSum, но сверяем всё равно: расхождение
        # означает, что зачислять по нашей цене нельзя.
        if state.out_sum is not None and abs(state.out_sum - order['amount_rub']) > 0.01:
            db.mark_order_checked(invoice_id, state.state_code)
            await notify_admin(
                f"⚠️ <b>Robokassa: сумма не совпала</b>\n"
                f"Счёт: <code>{invoice_id}</code>, пользователь: <code>{order['user_id']}</code>\n"
                f"Ожидали {order['amount_rub']} ₽, получили {state.out_sum} ₽. "
                f"Заказ ({order['kind']}) НЕ начислен."
            )
            return 'amount_mismatch'

        # Реферальный эквивалент подписки считается здесь, а не в db: денежную
        # сумму в запросы переводит ценовая сетка, а она живёт в bot.py.
        ref_qty = (unlimited_ref_qty()
                   if order['kind'] == db.ORDER_KIND_UNLIMITED else None)

        credited = db.credit_order(invoice_id, state.state_code, state.op_key,
                                   ref_qty=ref_qty)
        if credited is None:
            return 'already'  # успели зачислить в другом проходе

        await deliver_paid_order(credited)
        return 'paid'

    if state.is_canceled:
        db.set_order_status(invoice_id, 'canceled', state.state_code)
        logging.info("Заказ %s отменён (State.Code=%s)", invoice_id, state.state_code)
        return 'canceled'

    # Промежуточные состояния: 5 — ждём оплату, 50 — деньги у покупателя списаны,
    # но магазину не зачислены, 20/80 — холд и проверка безопасности. Начисляем
    # только по 100, а про залипшие состояния сообщаем админу — но один раз,
    # в момент смены статуса, иначе это будет сообщение каждые 30 секунд.
    if state.state_code != order['state_code'] and state.state_code in (
        robokassa.OpState.HOLD, robokassa.OpState.SECURITY_CHECK, robokassa.OpState.RECEIVED
    ):
        await notify_admin(
            f"ℹ️ <b>Robokassa: заказ в промежуточном статусе</b>\n"
            f"Счёт: <code>{invoice_id}</code>, пользователь: <code>{order['user_id']}</code>\n"
            f"State.Code=<code>{state.state_code}</code>. Начисления пока нет."
        )

    db.mark_order_checked(invoice_id, state.state_code)
    return 'pending'


def order_is_due(order: dict, now: datetime) -> bool:
    """Пора ли спрашивать статус этого заказа."""
    if not order['checked_at']:
        return True

    try:
        checked = datetime.fromisoformat(order['checked_at'])
        created = datetime.fromisoformat(order['created_at'])
    except ValueError:
        return True

    since_check = (now - checked).total_seconds()

    if order['status'] == 'expired':
        return since_check >= POLL_FINAL_INTERVAL
    if (now - created).total_seconds() <= POLL_FRESH_SECONDS:
        return True
    return since_check >= POLL_STALE_INTERVAL


async def poll_orders_once(session: aiohttp.ClientSession):
    expired = db.expire_stale_orders(ORDER_TTL_HOURS)
    if expired:
        logging.info("Просрочено неоплаченных заказов: %s", expired)

    now = datetime.now()
    for order in db.get_orders_to_poll(ORDER_FINAL_CHECK_DAYS):
        if poller_paused:
            return
        if not order_is_due(order, now):
            continue

        try:
            state = await robokassa.get_op_state(session, order['invoice_id'])
        except Exception as e:
            # Сеть моргнула или сервис недоступен — вернёмся к заказу на следующем
            # тике. Ронять цикл из-за одного заказа нельзя.
            logging.warning("Не удалось опросить заказ %s: %s", order['invoice_id'], e)
            continue

        await apply_op_state(order, state)
        await asyncio.sleep(POLL_REQUEST_GAP)


async def poll_orders_loop():
    """Фоновый опрос статусов. Живёт рядом с dp.start_polling на том же event loop.

    Схема без webhook: у бота нет домена, ResultURL некуда указывать, поэтому
    статус мы спрашиваем сами. Блокировать loop тут нечем — HTTP асинхронный
    (aiohttp), а обращения к SQLite такие же короткие, как в хендлерах.

    except Exception внутри while обязателен: без него первая же сетевая ошибка
    убила бы задачу навсегда и молча, а бот продолжил бы выглядеть живым.
    """
    if not robokassa.PAYMENTS_ENABLED:
        logging.info("Robokassa не настроена — фоновый опрос заказов не запущен")
        return

    logging.info("Опрос заказов Robokassa запущен, интервал %s с", POLL_INTERVAL)
    async with aiohttp.ClientSession() as session:
        while True:
            if poller_paused:
                logging.error("Опрос заказов остановлен из-за ошибки конфигурации Robokassa")
                return
            try:
                await poll_orders_once(session)
            except asyncio.CancelledError:
                raise
            except Exception as e:
                logging.error("Сбой цикла опроса Robokassa: %s", e, exc_info=True)
            await asyncio.sleep(POLL_INTERVAL)


