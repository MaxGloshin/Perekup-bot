def clean_city(text: str) -> str:
    """Приводит ответ пользователя к виду, пригодному для промпта. '' — не годится."""
    city = " ".join((text or "").split())
    if not city or len(city) > MAX_CITY_LEN:
        return ""
    # Ссылки и абзацы текста городом не являются
    if "http://" in city.lower() or "https://" in city.lower():
        return ""
    return city


