async def remind_unlimited_once() -> int:
    """Один проход по подпискам на исходе. Возвращает число отправленных писем.

    Право на отправку занимается в БД ДО send_message (claim_unlimited_reminder),
    а не после: иначе падение отправки на середине списка при следующем тике
    начало бы рассылку заново тем, кому уже ушло. Цена ошибки в другую сторону —
    непришедшее напоминание — заметно меньше, чем одно и то же сообщение
    четыре раза в сутки.
    """
    sent = 0
    for user_id, until_iso in db.users_to_remind_unlimited(UNLIMITED_REMIND_DAYS):
        if not db.claim_unlimited_reminder(user_id, until_iso):
            continue  # успел другой проход или человек продлил прямо сейчас

        try:
            until = datetime.fromisoformat(until_iso)
        except ValueError:
            continue

        left = until - datetime.now()
        days_left = max(left.days, 0)
        when = f"через {days_left} дн." if days_left else "сегодня"

        balance = db.purchased_balance(user_id)
        tail = (f"\n📦 Купленных запросов на балансе: {balance} — после окончания "
                f"подписки анализы пойдут из них."
                if balance else
                "\nПосле окончания подписки анализы будут списываться из купленных "
                "запросов, а их сейчас нет.")

        text = (
            f"⏳ Безлимит заканчивается {when} — {until.strftime('%d.%m.%Y')}.\n\n"
            f"Продлить — {UNLIMITED_PRICE} ₽ ещё на {UNLIMITED_DAYS} дней. "
            f"Дни прибавятся к текущему сроку, ничего не сгорит."
            f"{tail}"
        )

        try:
            await bot.send_message(user_id, text, reply_markup=renew_keyboard())
            sent += 1
        except TelegramForbiddenError:
            # Заблокировал бота — чистим строку тем же самолечением, что и
            # /broadcast. Подписка при этом теряется вместе с пользователем,
            # и это правильно: писать ему всё равно некуда.
            logging.info("Пользователь %s заблокировал бота — удаляю", user_id)
            db.delete_user(user_id)
        except TelegramRetryAfter as e:
            # Напоминаний за тик единицы, но если Telegram просит подождать —
            # ждём и пробуем один раз, иначе сообщение просто потеряется.
            await asyncio.sleep(e.retry_after)
            with contextlib.suppress(Exception):
                await bot.send_message(user_id, text, reply_markup=renew_keyboard())
                sent += 1
        except Exception as e:
            logging.warning("Не удалось напомнить о подписке пользователю %s: %s",
                            user_id, e)

        await asyncio.sleep(0.05)

    return sent


async def remind_unlimited_loop():
    """Фоновые напоминания о конце подписки. Живут рядом с опросом заказов.

    Отдельная задача, а не ветка внутри poll_orders_loop: тот выходит совсем,
    когда Robokassa не настроена или отдала битые реквизиты, — а напоминания
    к состоянию платёжного шлюза отношения не имеют.

    except Exception внутри while обязателен по той же причине, что и там: без
    него первая же ошибка убила бы задачу молча и навсегда.
    """
    logging.info("Напоминания о продлении подписки запущены, интервал %s с",
                 UNLIMITED_REMIND_INTERVAL)
    while True:
        try:
            sent = await remind_unlimited_once()
            if sent:
                logging.info("Напоминаний о продлении отправлено: %s", sent)
        except asyncio.CancelledError:
            raise
        except Exception as e:
            logging.error("Сбой цикла напоминаний о подписке: %s", e, exc_info=True)
        await asyncio.sleep(UNLIMITED_REMIND_INTERVAL)


async def main():
    db.init_db()
    logging.basicConfig(level=logging.INFO)
    config.log_startup()

    if robokassa.PAYMENTS_ENABLED:
        print(f"Бот запущен. Оплата через Robokassa включена "
              f"(режим: {'ТЕСТОВЫЙ' if robokassa.IS_TEST else 'боевой'}).")
    else:
        print("Бот запущен. Оплата выключена: в .env нет реквизитов Robokassa.")

    # Задачу держим переменной: asyncio хранит ссылки на задачи слабо, и без
    # своей ссылки сборщик мусора может убить опрос заказов на ходу.
    poller = asyncio.create_task(poll_orders_loop())
    reminder = asyncio.create_task(remind_unlimited_loop())
    try:
        await dp.start_polling(bot)
    finally:
        for task in (poller, reminder):
            task.cancel()
        for task in (poller, reminder):
            with contextlib.suppress(asyncio.CancelledError):
                await task


if __name__ == "__main__":
    asyncio.run(main())

