async def subscription_status(user_id: int) -> bool | None:
    """Подписка на REQUIRED_CHANNEL: True / False / None — проверить не удалось.

    Три исхода, а не два, потому что «человек не подписан» и «мы не смогли
    спросить» — разные факты, и решения по ним противоположные. Гейт при
    неизвестном исходе обязан пускать (см. is_subscribed ниже), а раздача
    подарков при неизвестном исходе обязана НЕ начислять: иначе сбой
    get_chat_member раздаёт бонус всей базе, а во время сбоя API его ещё и
    фармят нажатиями кнопки.

    None отдаётся и при пустом REQUIRED_CHANNEL: канала для проверки нет,
    значит и подписки мы не видели — для гейта это всё та же «неизвестность»,
    которая пускает, а для акции повод не начислять (дев-копия без канала).
    """
    if not REQUIRED_CHANNEL:
        return None

    try:
        member = await bot.get_chat_member(REQUIRED_CHANNEL, user_id)
    except Exception as e:
        logging.warning("Не удалось проверить подписку user=%s на %s: %s",
                        user_id, REQUIRED_CHANNEL, e)
        return None

    # aiogram отдаёт строковый enum — сравнение работает и так, но .value
    # страхует от любого другого типа
    status = getattr(member, "status", None)
    status = getattr(status, "value", status)

    if status in SUBSCRIBED_STATUSES:
        return True
    if status in NOT_SUBSCRIBED_STATUSES:
        return False

    # 'restricted' сам по себе не говорит, в канале человек или нет, — это
    # написано в is_member рядом. Раз ответ Telegram у нас на руках, читаем его,
    # иначе такой пользователь навсегда застрял бы в «не смог проверить» и
    # бонуса акции не увидел.
    is_member = getattr(member, "is_member", None)
    if isinstance(is_member, bool):
        logging.info("Статус подписки %r у user=%s, is_member=%s", status, user_id, is_member)
        return is_member

    logging.warning("Неизвестный статус подписки %r у user=%s — гейт пропустит",
                    status, user_id)
    return None


async def is_subscribed(user_id: int) -> bool:
    """Подписан ли пользователь — в трактовке гейта, fail-open.

    Любая ошибка (бота не сделали админом канала, канал переименован, сеть
    моргнула) — это наша проблема конфигурации, а не пользователя, поэтому
    неизвестный исход пускает. Запереть всех из-за собственной ошибки хуже,
    чем пропустить неподписанного.
    """
    return (await subscription_status(user_id)) is not False


