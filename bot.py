def normalize_domain(domain: str) -> str:
    """'https://www.Avito.RU/moskva' -> 'avito.ru'"""
    d = (domain or "").strip().lower()
    d = re.sub(r"^[a-z]+://", "", d).split("/")[0]
    return d[4:] if d.startswith("www.") else d


def domain_key(domain: str) -> str:
    """Регистрируемое имя без зоны: youla.ru и youla.link -> 'youla',
    market.yandex.ru -> 'yandex'.

    Сверять с grounding_chunks по полному домену нельзя: чанки отдают алиасы
    одной и той же площадки (youla.link против youla.ru), и строгое сравнение
    выбрасывало живые объявления. При этом разные сайты (i-shop.ru против
    ishop-my.ru) по этому ключу по-прежнему не совпадают.
    """
    labels = [part for part in domain.split(".") if part]
    if not labels:
        return ""
    return labels[-2] if len(labels) >= 2 else labels[0]


def is_classified_ad(domain: str) -> bool:
    """Доска объявлений (частный рынок) или магазин?"""
    return any(domain == d or domain.endswith("." + d) for d in CLASSIFIED_AD_DOMAINS)


def extract_seller_prices(caption: str) -> set:
    """Цены, названные в самом объявлении. Наблюдением рынка они не являются:
    оценивать лот по нему же самому — круговая ссылка, тянущая вилку вверх."""
    if not caption:
        return set()
    prices = set()
    for raw in re.findall(r"\d{1,3}(?:[\s  ]\d{3})+|\b\d{4,7}\b", caption):
        value = int(re.sub(r"[\s  ]", "", raw))
        if value >= 1000:
            prices.add(value)
    return prices


def chunk_domains(response) -> set:
    """Домены, реально попавшие в grounding_chunks. На практике домен лежит
    в title — поле domain у веб-чанков приходит пустым."""
    candidates = (response.candidates if response else None) or []
    if not candidates or not candidates[0].grounding_metadata:
        return set()
    domains = set()
    for chunk in (candidates[0].grounding_metadata.grounding_chunks or []):
        web = chunk.web
        if web:
            d = normalize_domain(web.domain or web.title or "")
            if d:
                domains.add(d)
    return domains


def drop_outliers(items: list):
    """Отсев выбросов по медиане и MAD (модифицированный z-score).

    Обычные квартильные усы на выборке из 3-5 цен вырождаются и выброс пропускают,
    а MAD устойчив: одиночная Юла за 30 000 рядом с Авито за 18 200 отсекается,
    при этом честно широкий разброс сохраняется целиком.
    """
    if len(items) < 3:
        return items, []

    values = [i["price"] for i in items]
    med = statistics.median(values)
    mad = statistics.median([abs(v - med) for v in values])

    def is_outlier(price):
        if mad == 0:
            # Все цены практически совпали — режем по относительному отклонению
            return abs(price - med) > 0.25 * med
        return 0.6745 * abs(price - med) / mad > 3.5

    keep, dropped = [], []
    for item in items:
        (dropped if is_outlier(item["price"]) else keep).append(item)
    return keep, dropped


def build_price_block(items: list) -> str:
    """Собирает блок цен для второго шага из разобранных данных.

    Текст генерирует код, а не модель: классификация частник/магазин идёт по
    домену, а не по пометке, которую модель ставила как попало. Выбросы
    отсекаются внутри каждой группы отдельно — у розницы свой уровень цен.
    """
    if not items:
        return NO_PRICE_DATA

    private, private_out = drop_outliers(
        sorted((i for i in items if i["is_private"]), key=lambda e: e["price"]))

    # Магазины и витрины до модели не доезжают вообще. Раньше они шли в блок
    # "верхней границей" — и ровно на них модель опиралась, когда частных цен
    # было мало, вытягивая вилку к рознице.
    shops = [i for i in items if not i["is_private"]]
    if shops or private_out:
        logging.info(
            "не пойдут в блок: магазинных %s, выбросов среди частных %s",
            [i["price"] for i in shops], [i["price"] for i in private_out]
        )

    # Ни одной частной цены — пусть модель честно считает по памяти с дисклеймером
    if not private:
        return NO_PRICE_DATA

    def fmt(entry):
        region = f", {entry['region']}" if entry.get("region") else ""
        title = f", {entry['title']}" if entry.get("title") else ""
        return f"- {entry['price']} руб. — {entry['domain']}{region}{title}"

    parts = []
    # Две цены — это не диапазон. drop_outliers() при такой выборке намеренно
    # молчит (обосновать выброс не на чем), поэтому честность перекладываем
    # на промпт: пусть модель сама скажет, что уверенность низкая.
    if len(private) < MIN_PRIVATE_PRICES:
        parts.append(
            f"МАЛО ДАННЫХ (частных объявлений всего {len(private)}) — "
            f"вилка может быть неточной."
        )
    parts.append("ЧАСТНЫЕ ОБЪЯВЛЕНИЯ (доски объявлений — это и есть частный рынок):")
    parts += [fmt(e) for e in private]
    return "\n".join(parts)


async def collect_prices(contents: list, caption: str = ""):
    """Шаг 1: нейтральный вызов с поиском. Возвращает (price_block, response).

    Персоны здесь нет намеренно — она заставляет модель игнорировать выдачу.
    Фоллбэка без tools нет: без поиска этот шаг бессмысленен, поэтому при любой
    ошибке честно отдаём NO_PRICE_DATA, а второй шаг об этом предупредит юзера.
    """
    try:
        response = await gemini_generate_content(
            model=GEMINI_MODEL,
            contents=contents,
            config=types.GenerateContentConfig(
                system_instruction=PRICE_COLLECTOR_PROMPT,
                tools=GEMINI_TOOLS,
                temperature=GEMINI_TEMPERATURE
            )
        )
    except Exception as e:
        logging.warning("Сбор цен не отработал: %s", e)
        return NO_PRICE_DATA, None

    seller_prices = extract_seller_prices(caption)
    known_keys = {domain_key(d) for d in chunk_domains(response)} - {""}

    items, dropped, unparsed, unconfirmed = [], 0, 0, 0
    for line in (response.text or "").splitlines():
        if not line.strip() or line.strip().upper().startswith(NO_PRICE_DATA):
            continue
        match = PRICE_LINE_RE.match(line)
        if not match:
            unparsed += 1
            continue

        price = int(re.sub(r"[\s  ]", "", match.group(1)))
        domain = normalize_domain(match.group(2))
        if price < 100 or not domain:
            continue
        # Цена из самого объявления — не независимое наблюдение рынка
        if price in seller_prices:
            dropped += 1
            continue

        # Домена нет в grounding_chunks — значит модель его не из выдачи взяла.
        # Такие записи до второго шага не доезжают вообще.
        if known_keys and domain_key(domain) not in known_keys:
            unconfirmed += 1
            continue

        items.append({
            "price": price,
            "domain": domain,
            "region": match.group(3).strip(),
            "title": match.group(4).strip(),
            "is_private": is_classified_ad(domain),
        })

    logging.info(
        "сбор цен: принято=%s не_разобрано=%s цена_продавца=%s "
        "домен_не_подтверждён=%s частных=%s",
        len(items), unparsed, dropped, unconfirmed,
        sum(1 for i in items if i["is_private"])
    )
    return build_price_block(items), response


def price_fact_line(price_block: str) -> str:
    """Блок собранных цен в том виде, в каком он уходит второму шагу.

    Отдельной функцией, а не строкой внутри вызова: формулировка «собраны
    поиском только что» описывает факт, и держать её в одном месте дешевле,
    чем ловить расхождение в тексте промпта.
    """
    return f"\n\nРЕАЛЬНЫЕ НАЙДЕННЫЕ ЦЕНЫ (собраны поиском только что):\n{price_block}"


async def run_verdict_step(verdict_contents: list, price_block: str, mode: str):
    """Шаг 2: вердикт по уже собранным ценам. Промпт выбирается режимом.

    Семафор здесь НЕ берётся: слот на оба шага держит ask_gemini_two_step.
    Вложенный acquire на неперевходимом семафоре — тихий дедлок под нагрузкой,
    поэтому слот остаётся заботой вызывающего.
    """
    return await gemini_generate_content(
        model=GEMINI_MODEL,
        contents=list(verdict_contents) + [price_fact_line(price_block)],
        config=types.GenerateContentConfig(
            # Промпт с персоной, но без tools — поэтому обязательно вариант,
            # не заикающийся про поиск (любой из VERDICT_PROMPTS такой).
            system_instruction=verdict_prompt(mode),
            temperature=GEMINI_TEMPERATURE
        )
    )


async def ask_gemini_two_step(price_contents: list, verdict_contents: list,
                              caption: str = "", mode: str = None):
    """Двухшаговая оценка: сначала собрать реальные цены, потом судить по ним.

    price_contents — что уходит сборщику (текст + одно фото, товар надо лишь
    опознать); verdict_contents — что уходит оценщику (текст + все фото, там
    разбор дефектов). mode влияет ТОЛЬКО на второй шаг: сбор цен нейтрален и
    одинаков для всех режимов.

    Возвращает (response, grounded, price_block, price_response):
    price_response нужен ради источников, на шаге 2 grounding_metadata нет.
    """
    async with gemini_semaphore:
        price_block, price_response = await collect_prices(price_contents, caption)
        response = await run_verdict_step(
            verdict_contents, price_block, mode or db.DEFAULT_MODE)

    return response, price_block != NO_PRICE_DATA, price_block, price_response


def extract_grounding(response):
    """Достаёт из ответа поисковые запросы модели и уникальные источники.

    Возвращает (queries, sources, total), где sources — список (подпись, ссылка),
    обрезанный до MAX_SOURCES_SHOWN, а total — сколько источников нашлось всего.
    total считается по метаданным, поэтому это единственное число об источниках,
    которому можно верить: сама модель их количества не знает и в промпте ей
    запрещено его называть.
    """
    # response может быть None: шаг сбора цен мог упасть целиком
    candidates = (response.candidates if response else None) or []
    if not candidates:
        return [], [], 0

    meta = candidates[0].grounding_metadata
    if not meta:
        return [], [], 0

    sources = []
    seen_uris = set()
    seen_labels = {}

    for chunk in (meta.grounding_chunks or []):
        web = chunk.web
        if not web or not web.uri or web.uri in seen_uris:
            continue
        seen_uris.add(web.uri)

        # На практике domain часто пустой, а в title лежит как раз домен
        label = web.domain or web.title or web.uri
        # Чистить подпись от []*_` больше не нужно: ссылка собирается тегом <a>,
        # а спецсимволы экранирует esc() в build_reply

        # Разные объявления с одной площадки — нормальная ситуация (четыре ссылки
        # на avito.ru), поэтому дедуп по URL, а повторам домена даём номер
        seen_labels[label] = seen_labels.get(label, 0) + 1
        if seen_labels[label] > 1:
            label = f"{label} #{seen_labels[label]}"

        sources.append((label, web.uri))

    return list(meta.web_search_queries or []), sources[:MAX_SOURCES_SHOWN], len(sources)


