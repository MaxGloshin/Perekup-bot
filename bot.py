@dp.callback_query(F.data.startswith("buy:"))
async def process_buy_click(callback: CallbackQuery):
    user_id = callback.from_user.id
    choice = callback.data.split(":", 1)[1]

    if not robokassa.PAYMENTS_ENABLED:
        await callback.answer("Оплата временно недоступна", show_alert=True)
        return

    if choice == "unlimited":
        await callback.answer()
        await send_payment_link(callback.message, user_id,
                                kind=db.ORDER_KIND_UNLIMITED)
        return

    if choice == "custom":
        awaiting_qty.add(user_id)
        # Вопрос про город, если он был открыт, снимаем: иначе введённое
        # количество уедет в user_city. В БД city_asked не взводим — вопрос
        # задастся заново при следующем /start.
        awaiting_city.discard(user_id)
        await callback.message.answer(
            f"🔢 Сколько запросов купить? Напиши число от 1 до {MAX_CUSTOM_QTY}.\n\n"
            "Цена за запрос: 1-9 — 30 ₽, 10-49 — 25 ₽, 50-199 — 20 ₽, от 200 — 10 ₽.\n"
            "Передумал — /cancel."
        )
        await callback.answer()
        return

    try:
        qty = int(choice)
    except ValueError:
        await callback.answer("Не понял пакет", show_alert=True)
        return

    await callback.answer()
    await send_payment_link(callback.message, user_id, qty)


