# занимая слот gemini_semaphore. Через прокси задержка только растёт, поэтому
# предел ставим явный: 180 с на вызов, до 360 с на оба шага анализа.
GEMINI_TIMEOUT_MS = 180_000

# Прокси периодически не отдаёт соединение вовсе: aiohttp падает с
# "Cannot connect to host <ip>:8000 ssl:… [Connect call failed]" ещё до того,
# как запрос уйдёт. Это не системная недоступность (без прокси Gemini отвечает
# 400 "User location is not supported" — блокировка по ASN хостера, обходить её
# прямым соединением бессмысленно), а флап самого прокси: похоже на лимит
# одновременных соединений на его стороне. Лечится повтором через паузу.
#
# Три попытки с удвоением базовой паузы — то есть ожидания 1 с и 2 с, третья
# попытка уже последняя. Больше держать пользователя в "анализирую" смысла нет:
# слот gemini_semaphore занят всё это время.
# max(1, …): ноль или минус в .env превратил бы цикл ниже в "ни одной попытки",
# то есть анализ падал бы, ни разу не сходив к Gemini. Выключить повторы —
# это 1, а не 0.
GEMINI_PROXY_RETRY_ATTEMPTS = max(
    1, int(os.getenv("GEMINI_PROXY_RETRY_ATTEMPTS", "3")))
GEMINI_PROXY_RETRY_BASE_DELAY_MS = max(
    0, int(os.getenv("GEMINI_PROXY_RETRY_BASE_DELAY_MS", "1000")))

# Что считаем сбоем СОЕДИНЕНИЯ, а не ответом Gemini.
#
# aiohttp.ClientConnectionError — общий предок для всего, что случается до
# того, как прокси отдал хоть какой-то HTTP-ответ: ClientConnectorError,
# ClientProxyConnectionError, ClientOSError, ServerDisconnectedError и
# ConnectionTimeoutError (таймаут именно установления соединения; он же
# подкласс asyncio.TimeoutError, так что отдельно перечислять его не нужно).
#
# Голый asyncio.TimeoutError сюда намеренно НЕ входит: aiohttp поднимает его,
# когда исчерпан общий таймаут запроса (GEMINI_TIMEOUT_MS, 180 с). Это не сбой
# коннекта, а медленный ответ модели, и три таких попытки — это девять минут
# занятого слота ради запроса, который и так дошёл до Gemini.
#
# Ошибки самого Gemini (google.genai.errors.APIError и его 503/400/429) не
# наследуются от aiohttp-исключений и через этот кортеж не проходят — у них
# своя природа и своя логика ожидания, и смешивать два счётчика попыток нельзя.
PROXY_CONNECT_ERRORS = (aiohttp.ClientConnectionError,)


def build_gemini_http_options() -> types.HttpOptions:
    """Собирает HttpOptions для genai.Client: таймаут и, если задан, прокси.

    Прокси приходится передавать двумя способами, потому что SDK ходит двумя
    транспортами. Асинхронные вызовы (а бот делает только их, через
    client.aio) идут через aiohttp, и async_client_args подставляются прямо
    в session.request(); синхронные — через httpx.Client, которому уходит
    client_args. Лишние ключи SDK отбрасывает сам, сверяясь с сигнатурой
    соответствующего клиента, так что proxy_headers до httpx не долетает.

    Заголовок Proxy-Authorization формируем руками, а не через proxy_auth:
    в aiohttp 3.14 этот параметр объявлен устаревшим и ругается на каждый
    запрос. Учти: httpx-ветка получает адрес прокси с логином внутри URL —
    другого способа передать ему авторизацию нет.
    """
    if not GEMINI_PROXY_URL:
        return types.HttpOptions(timeout=GEMINI_TIMEOUT_MS)

    parts = urlsplit(GEMINI_PROXY_URL)
    if parts.scheme not in ("http", "https") or not parts.hostname:
        raise RuntimeError(
            "GEMINI_PROXY_URL должен быть вида http://user:pass@ip:port "
            f"(получено: {parts.scheme or 'без схемы'}://…)"
        )

    host = parts.hostname if parts.port is None else f"{parts.hostname}:{parts.port}"
    async_args = {"proxy": urlunsplit((parts.scheme, host, "", "", ""))}
    if parts.username:
        creds = f"{unquote(parts.username)}:{unquote(parts.password or '')}"
        token = base64.b64encode(creds.encode("utf-8")).decode("ascii")
        async_args["proxy_headers"] = {"Proxy-Authorization": f"Basic {token}"}

    logging.info("Gemini ходит через прокси %s", host)
    return types.HttpOptions(
        timeout=GEMINI_TIMEOUT_MS,
        client_args={"proxy": GEMINI_PROXY_URL},
        async_client_args=async_args,
    )


