@dp.message(Command("promo_broadcast"))
async def promo_broadcast(message: Message):
    """Шаг 2 акции: одна рассылка по всей базе с подстановкой по статусу подписки.

    Подписанному уходит нейтральный хвост без кнопок (бонус ему уже начислен
    шагом 1), остальным — тот же текст плюс призыв и кнопки.
    """
    global promo_job

    if message.from_user.id != ADMIN_ID:
        return

    if not REQUIRED_CHANNEL:
        await message.answer(
            "REQUIRED_CHANNEL не задан — проверять подписку не у чего. "
            "Команда отключена."
        )
        return

    parts = message.text.split(maxsplit=1)
    if len(parts) < 2 or not parts[1].strip():
        await message.answer(PROMO_BROADCAST_USAGE)
        return

    body = parts[1].strip()

    if promo_job:
        await message.answer(f"Уже идёт: {promo_job}. Дождись окончания.")
        return

    promo_job = "рассылка акции"
    try:
        users = db.get_all_users()
        gap = PROMO_CHECK_GAP + PROMO_SEND_GAP
        await message.answer(
            f"Рассылка пошла. Пользователей: {len(users)}, "
            f"~{max(1, round(len(users) * gap / 60))} мин."
        )

        sent_plain = sent_with_button = blocked = failed = 0

        for i, user_id in enumerate(users, 1):
            status = await subscription_status(user_id)

            # Неизвестный статус ведём по ветке «не подписан», и это осознанно:
            # сказать неподписанному «бонус уже начислен» — соврать, а показать
            # кнопку тому, у кого бонус уже есть, безобидно — нажмёт и услышит
            # «бонус уже у тебя». Ошибка в эту сторону лечится сама.
            if status is True:
                text, keyboard = f"{body}\n\n{PROMO_TAIL_SUBSCRIBED}", None
            else:
                text, keyboard = f"{body}\n\n{PROMO_TAIL_UNSUBSCRIBED}", promo_keyboard()

            result = await send_promo_message(user_id, text, keyboard)
            if result == "ok" and keyboard is None:
                sent_plain += 1
            elif result == "ok":
                sent_with_button += 1
            elif result == "blocked":
                blocked += 1
            else:
                failed += 1

            if i % PROMO_PROGRESS_EVERY == 0:
                logging.info(
                    "рассылка %s: %s/%s, без_кнопки=%s с_кнопкой=%s "
                    "заблокировали=%s ошибок=%s",
                    PROMO_SOURCE, i, len(users), sent_plain, sent_with_button,
                    blocked, failed
                )

            if i % PROMO_ADMIN_PROGRESS_EVERY == 0:
                with contextlib.suppress(Exception):
                    await message.answer(
                        f"… {i}/{len(users)}, доставлено "
                        f"{sent_plain + sent_with_button}"
                    )

            await asyncio.sleep(PROMO_SEND_GAP)

        await message.answer(
            f"✅ Рассылка завершена.\n\n"
            f"Подписанным (без кнопок): {sent_plain}\n"
            f"Остальным (с кнопками): {sent_with_button}\n"
            f"Заблокировали бота: {blocked}\n"
            f"Прочие ошибки: {failed}"
        )
    finally:
        promo_job = None


async def send_promo_message(user_id: int, text: str, keyboard) -> str:
    """Отправка одного письма акции: 'ok' | 'blocked' | 'fail'.

    В отличие от обычного /broadcast обрабатывает 429: на проходе по всей базе
    Telegram почти наверняка попросит притормозить, а без повтора каждое такое
    письмо просто потерялось бы.
    """
    for attempt in (1, 2):
        try:
            await bot.send_message(user_id, text, reply_markup=keyboard)
            return "ok"
        except TelegramRetryAfter as e:
            logging.warning("Флуд-контроль на user=%s: ждём %s с (попытка %s)",
                            user_id, e.retry_after, attempt)
            await asyncio.sleep(e.retry_after + 1)
        except TelegramForbiddenError:
            # Пользователь заблокировал бота — та же самоочистка, что в /broadcast
            db.delete_user(user_id)
            return "blocked"
        except Exception as e:
            logging.warning("Не доставили письмо акции user=%s: %s", user_id, e)
            return "fail"
    return "fail"


# Диплинк вида t.me/<bot>?start=ref_123456. Разбираем строго: всё, что не
# подходит под шаблон, просто игнорируем — /start обязан работать всегда.
REF_PAYLOAD_RE = re.compile(r'^ref_(\d{1,20})$')

# Второй вид диплинка: t.me/<bot>?start=src_<тег> — метка источника трафика для
# /stats. Префиксы разные, поэтому ref_ и src_ взаимоисключающи в рамках одной
# ссылки сами по себе, без дополнительных проверок.
#
# Тег: только [A-Za-z0-9_-] и не длиннее MAX_SRC_TAG_LEN. Telegram сам ограничивает
# payload диплинка 64 символами, так что 32 — запас с двух сторон: и от чужих
# длинных utm-хвостов, и от мусора в разрезе /stats, где каждый тег это строка
# отчёта. Регулярка И есть валидация: не подошло — вернём None, и источник
# останется 'organic'. Ронять /start из-за кривой метки нельзя ни в каком случае.
MAX_SRC_TAG_LEN = 32
SRC_PAYLOAD_RE = re.compile(r'^src_([A-Za-z0-9_-]{1,%d})$' % MAX_SRC_TAG_LEN)


def parse_ref_payload(args: str | None) -> int | None:
    match = REF_PAYLOAD_RE.match((args or "").strip())
    return int(match.group(1)) if match else None


def parse_src_payload(args: str | None) -> str | None:
    """Тег источника из диплинка или None, если метки нет либо она невалидна."""
    match = SRC_PAYLOAD_RE.match((args or "").strip())
    return match.group(1) if match else None


def source_link(tag: str) -> str:
    """Ссылка для размещения в канале/рекламе. Симметрична referral_link()."""
    return f"https://t.me/{BOT_USERNAME}?start=src_{tag}"


def referral_link(user_id: int) -> str:
    return f"https://t.me/{BOT_USERNAME}?start=ref_{user_id}"


